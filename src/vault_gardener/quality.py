"""Quality against the hand-labeled sample (PRD evaluation hook, D-8, D-24).

Runs one tick on a fresh copy of the fixture vault (every note is new, so every note is classified and linked),
then compares the 20 labeled notes with `fixtures/labels.json`:
- tag precision / recall (micro, over the final tag set on each note),
- type accuracy,
- link precision (micro, over links in the managed Related block).
Each note is also scored by G0 `evaluation` with the seeded rubric `g5_note_labels_v1` (pass/fail lives in G0).
On the recorded fixtures these numbers describe the hand-written responses and their designed mistakes, not a model.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from vault_gardener import note
from vault_gardener.config import LABELS_FILE, Limits, g0_db_path
from vault_gardener.simulate import simulate


def _level(hit: int, total: int) -> str:
    if total == 0:
        return "full"
    return "full" if hit == total else ("none" if hit == 0 else "partial")


def run_quality(state_dir: Path, labels_file: Path | None = None, limits: Limits | None = None) -> dict[str, Any]:
    labels = json.loads((labels_file or LABELS_FILE).read_text(encoding="utf-8"))["notes"]
    sim = simulate(state_dir, ticks=1, limits=limits, events_file=None)
    from vault_gardener.layer import Layer

    layer = Layer(g0_db_path(state_dir))
    try:
        per: list[dict[str, Any]] = []
        tp_tags = n_pred_tags = n_true_tags = 0
        type_ok = 0
        tp_links = n_links = 0
        g0_passed = 0
        for path, lab in labels.items():
            text = (sim.vault / path).read_text(encoding="utf-8")
            n = note.parse(text)
            pred_tags, true_tags = set(n.tags()), set(lab["tags"])
            hit = len(pred_tags & true_tags)
            tp_tags += hit
            n_pred_tags += len(pred_tags)
            n_true_tags += len(true_tags)
            t_ok = n.type() == lab["type"]
            type_ok += t_ok
            links = list(n.related)
            good_links = [s for s in links if s in lab["related"]]
            tp_links += len(good_links)
            n_links += len(links)
            item = {
                "type_match": "yes" if t_ok else "no",
                "tags_recall": _level(hit, len(true_tags)),
                "tags_precision": _level(hit, len(pred_tags)),
                "links_precision": "no_links" if not links else _level(len(good_links), len(links)),
            }
            ev = layer.evaluate(item, run_id="g5-quality")
            g0_passed += bool(ev.ok and ev.passed)
            per.append({
                "path": path, "type": n.type(), "type_expected": lab["type"], "tags": sorted(pred_tags), "tags_expected": sorted(true_tags),
                "missing_tags": sorted(true_tags - pred_tags), "wrong_tags": sorted(pred_tags - true_tags),
                "links": links, "wrong_links": [s for s in links if s not in lab["related"]],
                "g0_passed": bool(ev.ok and ev.passed), "g0_total": ev.total, "g0_notes": ev.notes,
            })
        rep = {
            "labeled_notes": len(labels),
            "tag_precision": round(tp_tags / n_pred_tags, 4) if n_pred_tags else None,
            "tag_recall": round(tp_tags / n_true_tags, 4) if n_true_tags else None,
            "type_accuracy": round(type_ok / len(labels), 4),
            "link_precision": round(tp_links / n_links, 4) if n_links else None,
            "links_written": n_links,
            "tags_counts": {"correct": tp_tags, "on_notes": n_pred_tags, "expected": n_true_tags},
            "g0_rubric_passed": g0_passed,
            "per_note": per,
            "sim": sim.summary(),
        }
    finally:
        layer.close()
    return rep


def render_markdown(rep: dict[str, Any]) -> str:
    tc = rep["tags_counts"]
    lines = [
        "# Vault Gardener — quality report (recorded fixtures)",
        "",
        "**These numbers describe the hand-written recorded responses in `fixtures/recorded.json` and their designed mistakes "
        "(D-24), scored against the hand-labeled sample in `fixtures/labels.json`. They are not a measurement of any model.**",
        "",
        "Generated by `gardener quality` (one tick on a fresh copy of the fixture vault; every note is new).",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Labeled notes | {rep['labeled_notes']} |",
        f"| Tag precision | {rep['tag_precision']} ({tc['correct']} of {tc['on_notes']} tags on the notes are labeled tags) |",
        f"| Tag recall | {rep['tag_recall']} ({tc['correct']} of {tc['expected']} labeled tags are on the notes) |",
        f"| Type accuracy | {rep['type_accuracy']} |",
        f"| Link precision | {rep['link_precision']} (of {rep['links_written']} links written) |",
        f"| Notes passing G0 rubric `g5_note_labels_v1` | {rep['g0_rubric_passed']} of {rep['labeled_notes']} |",
        "",
        "| Note | Type (expected) | Missing tags | Wrong tags | Wrong links | G0 |",
        "|---|---|---|---|---|---|",
    ]
    for p in rep["per_note"]:
        lines.append(f"| `{p['path']}` | {p['type']} ({p['type_expected']}) | {', '.join(p['missing_tags']) or '—'} | "
                     f"{', '.join(p['wrong_tags']) or '—'} | {', '.join(p['wrong_links']) or '—'} | {'pass' if p['g0_passed'] else 'fail'} |")
    lines += ["", "A note the Classifier could not tag (malformed response) keeps its owner's frontmatter; if it is in the sample its "
                  "type and tags count against these figures.", ""]
    return "\n".join(lines)
